package com.porest.desk.asset.type;

/**
 * 자산 잔액의 채널 — 실제 증권 계좌처럼 예수금과 평가금액을 따로 든다.
 *
 * <p>둘을 한 칸에 담으면 서로 덮어쓴다. 보유 종목이 달린 투자 자산은 평가액이
 * {@link BalanceSourceType#VALUATION} 절대 앵커로 계속 찍히는데, 앵커가 하나 찍히면
 * 그 앞의 flow 는 전부 무효가 되므로 증권계좌로 넣은 이체가 조용히 사라졌다.
 * 보내는 쪽 계좌에서는 flow −N 이 남아 있어 순자산이 그만큼 줄어든 채로 고정된다.
 *
 * <p>채널을 나누면 평가액 앵커가 예수금을 건드리지 않는다.
 * <pre>
 *   잔액 = 예수금(CASH) + 평가금액(HOLDING)
 *   예수금   = (기준시각 이하 마지막 CASH 절대 앵커) + 그 이후 CASH flow 합
 *   평가금액 = (기준시각 이하 마지막 HOLDING 절대 앵커)   — flow 없음
 * </pre>
 */
public enum BalanceChannel {
    /** 예수금·현금 — 이체·거래가 쌓이는 곳. 투자가 아닌 자산은 전부 이 채널만 쓴다. */
    CASH,
    /** 보유 종목 평가금액 — 시세×수량으로 통째 갱신된다. 절대 앵커만 존재한다. */
    HOLDING,
}
