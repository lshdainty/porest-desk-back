package com.porest.desk.common.validation;

/**
 * 사용자가 고르는 색의 형식 — {@code #RRGGBB} 한 벌뿐이다.
 *
 * <p>종전엔 아무 문자열이나 그대로 저장됐다. {@code "not-a-color"} 로 만든 라벨,
 * {@code "zzz"} 로 만든 메모가 실제로 200 을 받았고(QA 2026-09-07 #86), 그 행은
 * 화면에서 색이 안 칠해지거나 <b>다른 색으로 보이는</b> 상태로 남는다 —
 * 저장은 됐는데 고른 색이 사라지므로 사용자는 무엇이 틀렸는지 알 수 없다.
 *
 * <p><b>왜 여기 한 곳인가.</b> 색을 받는 자리가 여덟 군데(라벨 · 메모 · 카테고리 ·
 * 일정 · 캘린더 · 저축목표 · 자산 · 태그)라, 정규식을 각자 적어 두면 다음에 색을
 * 받는 자리가 하나 더 생길 때 아홉 번째 리터럴이 생긴다. {@link FieldLimits} 가
 * 길이에 대해 하는 일을 색에 대해 한다.
 *
 * <h4>왜 6자리 hex 만인가</h4>
 * 웹·앱이 저장용으로 보내는 값이 그것뿐이라서다(2026-09-07 양쪽 코드로 확인).
 * 두 클라이언트 모두 {@code porest-design} 팔레트의 base hex(예: {@code #2c70bf})를
 * 그대로 싣고, {@code #fff} 같은 3자리는 아이콘 획 색 같은 <b>화면 안에서만</b> 쓰는 값이라
 * 요청 본문에 실리지 않는다. 서버가 심는 기본값도 전부 6자리다(예: {@code #9E9E9E}) —
 * 그래서 대소문자를 둘 다 받는다. {@code porest-sql} 의 색 리터럴 218개도 전부 6자리다.
 *
 * <p>메모만 컬럼이 {@code varchar(7)} 이고 나머지는 {@code varchar(20)} 인데, 이 형식은
 * 가장 좁은 컬럼에도 들어간다.
 */
public interface ColorFormat {

    /** {@code #RRGGBB} — 대소문자 무관. 빈 문자열은 통과하지 않는다(클라이언트는 아예 안 보낸다). */
    String HEX_RGB = "^#[0-9a-fA-F]{6}$";

    /**
     * 안내 문구. 내부 필드명 대신 사용자가 아는 말로 쓴다(QA #75) — 색은 화면에서
     * 견본을 눌러 고르는 값이라 "형식" 을 설명해도 할 수 있는 일이 없다.
     */
    String MESSAGE = "색상을 다시 골라 주세요";
}
