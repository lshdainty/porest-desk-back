package com.porest.desk.common.validation;

/**
 * 요청 금액 상한. 문자열 길이의 {@link FieldLimits} 와 같은 자리에 둔다.
 *
 * <p>컬럼은 전부 {@code bigint} 라 99조도 들어간다 — 0 을 몇 개 더 찍는 오타를 막는 건
 * 이 상수뿐이다. 종전엔 거래(ExpenseApiDto)에만 상한이 있고 계좌 잔액·예산·저축목표·반복거래에는
 * 없어서, 같은 앱 안에서 어떤 칸은 100억에서 막히고 어떤 칸은 99조가 통과했다
 * (QA 2026-09-03 #17 #48 #52 #54). <b>층을 둘로만 나눠</b> 다음에 금액 칸이 생겨도
 * 리터럴을 새로 고르지 않게 한다.
 *
 * <p>여기 숫자를 올려도 DB 는 안 막지만, 화면 안내 문구(웹·앱의 "…까지 입력할 수 있어요")와
 * 짝이므로 <b>양쪽을 같이</b> 고쳐야 한다.
 */
public interface AmountLimits {

    /**
     * 거래 한 건(100억원). 지출·수입·예산·저축목표·반복거래가 전부 이 층이다 —
     * 반복거래는 결국 거래를 찍으므로 거래보다 크면 상한을 우회하는 경로가 된다.
     */
    long MAX_TX_AMOUNT = 10_000_000_000L;

    /**
     * 계좌 잔액·한도(1,000억원, 사용자 확정).
     *
     * <p>거래와 자리수가 다른 건 의도다 — 잔액은 예금·대출 원금이라 거래 한 건보다 크다.
     */
    long MAX_BALANCE = 100_000_000_000L;
}
