package com.porest.desk.dataimport.sms.service;

/**
 * 파싱 신뢰도 — 클라이언트가 "그냥 저장해도 되는 건지" 를 판단하는 기준.
 *
 * <p>파서는 절대 스스로 저장하지 않는다. 이 값은 화면에서 어디까지 사용자에게
 * 물어볼지를 정할 뿐이다 — HIGH 면 확인 버튼 하나, LOW 면 필드를 열어 고치게 한다.
 */
public enum SmsConfidence {
    /** 카드사·금액·일시·가맹점이 모두 잡혔다. 사용자는 확인만 하면 된다. */
    HIGH,
    /** 금액은 확실하나 일시나 가맹점 중 하나가 비었다. 빈 칸을 채우게 한다. */
    MEDIUM,
    /** 금액 외에는 대부분 불확실하다(외화·미등록 카드사 등). 전 필드를 열어 준다. */
    LOW
}
